export const allLessons = stages.flatMap((stage) =>
  stage.lessons.map((lesson, i) => ({
    ...lesson,
    stageId: stage.id,
    stageN: stage.n,
    stageTitle: stage.title,
    index: i + 1,
  }))
);

export const lessonCount = allLessons.length;

export function findLesson(slug) {
  return allLessons.find((l) => l.slug === slug) || null;
}

export function findStage(id) {
  return stages.find((s) => s.id === id) || null;
}